def eggs():
    for name, (base, spot) in EGGS.items():
        c = Canvas(16, 16, 0)
        b, s = hex_rgb(base), hex_rgb(spot)
        pal = {"K": shade(b, 0.45), "1": b, "2": s}
        c.mask_from(EGG, pal)
        # subtle highlight
        c.set(6, 4, shade(b, 1.25)); c.set(5, 5, shade(b, 1.2))
        c.save("textures", "item", name + ".png")


def discs():
    for name, label in DISCS.items():
        c = Canvas(16, 16, 0)
        dark = hex_rgb("1e1e22")
        for y in range(16):
            for x in range(16):
                d = ((x - 7.5) ** 2 + (y - 7.5) ** 2) ** 0.5
                if d <= 7.2:
                    c.set(x, y, dark if int(d) % 2 else hex_rgb("2a2a30"))
                if d <= 3.2:
                    c.set(x, y, hex_rgb(label))
                if d <= 0.9:
                    c.set(x, y, hex_rgb("0e0e10"))
        c.set(5, 5, hex_rgb("4a4a52")); c.set(10, 3, hex_rgb("3e3e46"))
        c.save("textures", "item", name + ".png")


def main():
    for name, rows in ITEMS.items():
        draw(name, rows)
    eggs()
    discs()
    print(f"{len(ITEMS) + len(EGGS) + len(DISCS)} item textures written")


if __name__ == "__main__":
    main()
